def reform_identity(
    payload: Optional[Union[Mapping[str, Any], Sequence[Any]]],
    representation: Optional[ReformRepresentation] = None,
    *,
    name: Optional[str] = None,
) -> ReformIdentity:
    """Bind a reform payload (a JSON object or array) by digest.

    ``None`` or an empty payload means current law. The payload is digested
    exactly as given in its representation, after strict JSON conversion; no
    normalization across representations is attempted. A policyengine-uk
    ``Scenario`` goes through :func:`scenario_reform_identity`; for
    ``Scenario.from_reform(d)`` bind ``d`` with
    ``"policyengine-uk.reform_dict/v1"``.
    """

    if payload is None:
        return ReformIdentity(kind="current_law", name=name)
    if isinstance(payload, (str, bytes)) or not isinstance(
        payload, (Mapping, list, tuple)
    ):
        raise ReceiptError(
            f"A reform payload is a JSON object or array, not {type(payload).__name__}."
        )
    if not payload:
        return ReformIdentity(kind="current_law", name=name)
    if representation is None:
        raise ReceiptError("A non-empty reform needs its representation.")
    if representation == "policyengine-uk.scenario/v1":
        raise ReceiptError("Bind a Scenario with scenario_reform_identity().")
    digest = _payload_sha256({"representation": representation, "payload": payload})
    return ReformIdentity(
        kind="reform", representation=representation, reform_sha256=digest, name=name
    )


