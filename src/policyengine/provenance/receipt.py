"""Execution receipts: exactly what produced a PolicyEngine result (schema v1).

A receipt travels with a published number (a dashboard row, a briefing
figure, an API response) and names everything that determined it:

- the wrapper, country model and core versions that actually ran, read
  from the installed distributions rather than from the bundle manifest;
- the data release, its build identity, and the dataset's revision and
  SHA-256 as read from the bytes that were simulated;
- the certificate that admitted that model and data pair, as a digest of
  the bundle's certification record;
- the reform and baseline, as digests of their canonical representation;
- the fiscal-year convention that gives the reported years their meaning.

Digests use RFC 8785 canonical JSON (:mod:`policyengine.provenance.canonical`),
so a JavaScript or Python consumer can recompute them. The JSON Schema for
this contract ships in the wheel at
``policyengine/data/schemas/execution_receipt.v1.schema.json`` and is
regenerated by ``scripts/generate_receipt_schemas.py``.

Schema v1 rules that hold for every valid receipt:

- ``certificate`` is present only when the certificate covers the installed
  model version and the simulated dataset bytes; otherwise the receipt is
  explicitly ``certification_status="uncertified"``.
- ``years`` is sorted and unique, and every reported year has the meaning
  ``fiscal_year`` gives it.
- The execution identity digest covers only what determines the execution
  (wrapper, model, core, data, certificate); two results with the same
  digest ran on the same runtime and data. The receipt digest also covers
  reform, baseline, years, convention and outputs.

Adding an optional field is a compatible v1 change. Removing or redefining a
field, or changing a digest's preimage, requires schema v2.
"""

