class ReformIdentity(_Contract):
    """A reform or baseline, bound by the digest of its canonical form."""

    kind: Literal["current_law", "reform"] = Field(
        description="current_law means no parameter or structural change."
    )
    representation: Optional[ReformRepresentation] = None
    reform_sha256: Optional[str] = Field(
        default=None,
        pattern=SHA256_PATTERN,
        description=(
            "SHA-256 of the RFC 8785 serialisation of {'representation': ..., "
            "'payload': ...}, nulls kept (unlike content_sha256)."
        ),
    )
    binding: Literal["content", "code_revision"] = Field(
        default="content",
        description=(
            "content: the digest determines the reform's behaviour. "
            "code_revision: the reform runs a module-level Python function, "
            "bound by its source, its module's source, its default arguments "
            "and the caller's code revision."
        ),
    )
    name: Optional[str] = Field(
        default=None, description="Human label; part of no digest."
    )

    # Stored outside Pydantic fields and private attributes so equality,
    # serialization and digests ignore this process-local re-check handle.
    _recompute_identity: ClassVar[Optional[Callable[[], ReformIdentity]]] = None

    def _recheck(self) -> ReformIdentity:
        """Recompute a live identity; loaded identities have no handle."""

        if self._recompute_identity is None:
            return self
        try:
            recomputed = self._recompute_identity()
        except ReceiptError as exc:
            raise ReceiptError(
                f"The modifier changed after its identity was computed: {exc}"
            ) from exc
        differences = [
            field
            for field in type(self).model_fields
            if getattr(self, field) != getattr(recomputed, field)
        ]
        if differences:
            raise ReceiptError(
                "The modifier changed after its identity was computed: "
                + ", ".join(differences)
                + " differs."
            )
        return recomputed

    @model_validator(mode="after")
    def _current_law_has_no_digest(self) -> ReformIdentity:
        if self.kind == "current_law":
            if self.reform_sha256 is not None or self.representation is not None:
                raise ValueError("current_law carries no representation or digest.")
            if self.binding != "content":
                raise ValueError("current_law is bound by content.")
        elif self.reform_sha256 is None or self.representation is None:
            raise ValueError("A reform needs a representation and a reform_sha256.")
        return self


