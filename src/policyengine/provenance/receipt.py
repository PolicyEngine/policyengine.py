class ReformIdentity(_Contract):
    """A reform or baseline, bound by the digest of its canonical form."""

    kind: Literal["current_law", "reform"] = Field(
        description="current_law means no parameter or structural change."
    )
    representation: Optional[ReformRepresentation] = None
    reform_sha256: Optional[str] = Field(
        default=None,
        pattern=SHA256_PATTERN,
        description=(
            "RFC 8785 SHA-256 of {'representation': ..., 'payload': ...}; "
            "see reform_identity()."
        ),
    )
    binding: Literal["content", "code_revision"] = Field(
        default="content",
        description=(
            "content: the digest determines the reform's behaviour. "
            "code_revision: the reform runs Python code (a simulation "
            "modifier) bound only by its source digest and the caller's code "
            "revision; values captured in closures are not bound."
        ),
    )
    name: Optional[str] = Field(
        default=None, description="Human label; not part of the digest."
    )

    @model_validator(mode="after")
    def _current_law_has_no_digest(self) -> ReformIdentity:
        if self.kind == "current_law":
            if self.reform_sha256 is not None or self.representation is not None:
                raise ValueError("current_law carries no representation or digest.")
            if self.binding != "content":
                raise ValueError("current_law is bound by content.")
        elif self.reform_sha256 is None or self.representation is None:
            raise ValueError("A reform needs a representation and a reform_sha256.")
        return self


class FiscalYearConvention(_Contract):
    """What an annual period label means in this result."""

    convention: Literal["uk_fiscal_year", "calendar_year"]
    year_label: Literal["start_year"] = Field(
        default="start_year",
        description="Year Y labels the period that starts in Y (UK: 2027 is 2027-28).",
    )
    period_start: str = Field(
        pattern=r"^\d{2}-\d{2}$",
        description="Month-day the labelled period starts: 04-06 (UK), 01-01 (calendar).",
    )
    parameter_annualisation: str = Field(
        description=(
            "Identifier of the annualisation rule the recorded model version "
            "implements, e.g. policyengine-uk/fiscal-year-parameters."
        )
    )

    @model_validator(mode="after")
    def _consistent(self) -> FiscalYearConvention:
        expected = {"uk_fiscal_year": "04-06", "calendar_year": "01-01"}[
            self.convention
        ]
        if self.period_start != expected:
            raise ValueError(
                f"{self.convention} periods start on {expected}, not {self.period_start}."
            )
        return self


class RuntimeContext(_Contract):
    """Where the execution ran. Not part of the execution identity."""

    python_version: str
    platform: str
    ci_run_url: Optional[str] = None


class ExecutionReceipt(_Contract):
    """Schema v1 execution receipt. See the module docstring for its rules."""

    SCHEMA_ID: ClassVar[str] = (
        "https://policyengine.org/schemas/execution_receipt.v1.json"
    )

    schema_version: Literal[1]
    receipt_type: Literal["policyengine.execution_receipt"]
    country_id: Literal["uk", "us"]
    wrapper: WrapperIdentity
    model: PackageIdentity
    core: PackageIdentity
    data: DataIdentity
    certification_status: Literal["certified", "uncertified"]
    certificate: Optional[CertificateIdentity] = None
    reform: ReformIdentity
    baseline: ReformIdentity
    fiscal_year: FiscalYearConvention
    years: list[int] = Field(min_length=1)
    outputs_sha256: Optional[str] = Field(
        default=None,
        pattern=SHA256_PATTERN,
        description="RFC 8785 SHA-256 of the canonical output payload this receipt binds.",
    )
    runtime: Optional[RuntimeContext] = None

    @field_validator("years")
    @classmethod
    def _sorted_unique_years(cls, years: list[int]) -> list[int]:
        if years != sorted(set(years)):
            raise ValueError("years must be sorted and unique.")
        return years

    @model_validator(mode="after")
    def _certificate_matches_execution(self) -> ExecutionReceipt:
        expected_convention = {"uk": "uk_fiscal_year", "us": "calendar_year"}[
            self.country_id
        ]
        if self.fiscal_year.convention != expected_convention:
            raise ValueError(
                f"{self.country_id.upper()} receipts report {expected_convention} periods."
            )
        if self.certification_status == "uncertified":
            if self.certificate is not None:
                raise ValueError("An uncertified receipt carries no certificate.")
            return self
        certificate = self.certificate
        if certificate is None:
            raise ValueError("A certified receipt needs a certificate.")
        if certificate.country_id != self.country_id:
            raise ValueError("Certificate country differs from the receipt country.")
        if certificate.certified_for_model_version != self.model.version:
            raise ValueError(
                "The certificate covers model "
                f"{certificate.certified_for_model_version}, but "
                f"{self.model.version} ran."
            )
        if certificate.certified_dataset_sha256 != self.data.dataset_sha256:
            raise ValueError(
                "The certificate covers different dataset bytes from those simulated."
            )
        if certificate.bundle_version != self.wrapper.version:
            raise ValueError(
                "The certificate belongs to a different policyengine.py version."
            )
        return self

    # --- Digests ---------------------------------------------------------
    def execution_identity(self) -> dict[str, Any]:
        """The canonical value that identifies the runtime and data."""

        identity: dict[str, Any] = {
            "schema_version": self.schema_version,
            "country_id": self.country_id,
            "wrapper": self.wrapper.canonical_payload(),
            "model": self.model.canonical_payload(),
            "core": self.core.canonical_payload(),
            "data": self.data.canonical_payload(),
            "certification_status": self.certification_status,
        }
        if self.certificate is not None:
            identity["certificate"] = self.certificate.canonical_payload()
        return identity

    @property
    def execution_identity_sha256(self) -> str:
        return canonical_sha256(self.execution_identity())

    def receipt_payload(self) -> dict[str, Any]:
        """The canonical value the receipt digest covers (everything but runtime)."""

        payload = self.canonical_payload()
        payload.pop("runtime", None)
        return payload

    @property
    def receipt_sha256(self) -> str:
        return canonical_sha256(self.receipt_payload())

    def to_canonical_json(self) -> bytes:
        """RFC 8785 bytes of the full receipt, including runtime context."""

        return canonical_json(self.canonical_payload())

    @classmethod
    def json_schema(cls) -> dict[str, Any]:
        """JSON Schema (2020-12) for the receipt, with its cross-field rules.

        JSON Schema cannot express every v1 rule; the ones it cannot are
        listed under ``x-policyengine-rules`` and must be checked by
        consumers that do not use this Python model.
        """

        schema = cls.model_json_schema()
        return {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": cls.SCHEMA_ID,
            **schema,
            "x-policyengine-rules": list(CROSS_FIELD_RULES),
            "x-policyengine-digests": dict(DIGEST_RULES),
        }


# --- Helpers -------------------------------------------------------------


def normalize_distribution_name(name: str) -> str:
    """PEP 503 normalization: lowercase, runs of -_. become -."""

    return re.sub(r"[-_.]+", "-", name).lower()


def uk_fiscal_year_convention() -> FiscalYearConvention:
    """The UK convention: year Y is the fiscal year 6 April Y to 5 April Y+1."""

    return FiscalYearConvention(
        convention="uk_fiscal_year",
        period_start="04-06",
        parameter_annualisation="policyengine-uk/fiscal-year-parameters",
    )


def fiscal_year_label(year: int, convention: FiscalYearConvention) -> str:
    """Display label for a reported year: ``2027-28`` (UK) or ``2027``."""

    if convention.convention == "uk_fiscal_year":
        return f"{year}-{(year + 1) % 100:02d}"
    return str(year)


def certificate_sha256(certification_record: Mapping[str, Any]) -> str:
    """Digest of a bundle manifest's ``data_releases.<country>`` record."""

    return content_sha256(certification_record)


def reform_identity(
    payload: Optional[Union[Mapping[str, Any], Sequence[Any]]],
    representation: Optional[ReformRepresentation] = None,
    *,
    name: Optional[str] = None,
) -> ReformIdentity:
    """Bind a reform payload by digest; ``None`` or empty means current law.

    The payload is digested exactly as given in its representation; no
    normalization across representations is attempted.
    """

    if isinstance(payload, (str, bytes)):
        raise ReceiptError("A reform payload is a JSON object or array, not a string.")
    if payload is None or not payload:
        return ReformIdentity(kind="current_law", name=name)
    if representation is None:
        raise ReceiptError("A non-empty reform needs its representation.")
    digest = content_sha256({"representation": representation, "payload": payload})
    return ReformIdentity(
        kind="reform",
        representation=representation,
        reform_sha256=digest,
        name=name,
    )


def _json_value(value: Any) -> Any:
    """Round-trip through JSON so dates and tuples take their JSON form."""

    return json.loads(json.dumps(value, default=str, allow_nan=False))


def content_sha256(value: Any) -> str:
    """Receipt digest of a JSON-able value: nulls dropped, RFC 8785, SHA-256."""

    return canonical_sha256(drop_null_members(_json_value(value)))


def installed_package_identity(
    name: str,
    *,
    wheel_sha256: Optional[str] = None,
    wheel_sha256_evidence: Optional[HashEvidence] = None,
) -> PackageIdentity:
    """Identity of an installed distribution, with an optional verified hash.

    Without explicit evidence, the installer's PEP 610 ``direct_url.json``
    archive hash is used when present; a bundle manifest's wheel hash is
    never assumed to describe installed files.
    """

    version = metadata.version(name)
    if wheel_sha256 is None:
        archive_hash = _installer_archive_sha256(name)
        if archive_hash is not None:
            wheel_sha256 = archive_hash
            wheel_sha256_evidence = "installer_archive_hash"
    return PackageIdentity(
        name=name,
        version=version,
        wheel_sha256=wheel_sha256,
        wheel_sha256_evidence=wheel_sha256_evidence if wheel_sha256 else None,
    )


def _installer_archive_sha256(name: str) -> Optional[str]:
    try:
        text = metadata.distribution(name).read_text("direct_url.json")
    except metadata.PackageNotFoundError:
        return None
    if not text:
        return None
    try:
        archive = json.loads(text).get("archive_info") or {}
    except ValueError:
        return None
    hashes = archive.get("hashes") or {}
    candidate = hashes.get("sha256")
    if candidate is None:
        legacy = archive.get("hash") or ""
        if legacy.startswith("sha256="):
            candidate = legacy.removeprefix("sha256=")
    if candidate and _SHA256.match(candidate):
        return candidate
    return None


def _wrapper_identity(git_sha: Optional[str]) -> WrapperIdentity:
    package = installed_package_identity("policyengine")
    return WrapperIdentity(**package.model_dump(), git_sha=git_sha)


def _country_model_package(country_id: str) -> str:
    return {"uk": "policyengine-uk", "us": "policyengine-us"}[country_id]


def build_execution_receipt(
    *,
    country_id: Literal["uk", "us"],
    dataset_path: Union[str, Path],
    years: Sequence[int],
    reform: Optional[ReformIdentity] = None,
    baseline: Optional[ReformIdentity] = None,
    dataset: Optional[str] = None,
    outputs: Optional[Any] = None,
    package_hashes: Optional[Mapping[str, tuple[str, HashEvidence]]] = None,
    wrapper_git_sha: Optional[str] = None,
    qualification_receipt_sha256: Optional[str] = None,
    bundle: Optional[Mapping[str, Any]] = None,
    ci_run_url: Optional[str] = None,
) -> ExecutionReceipt:
    """Build a receipt for a result computed in this process.

    Versions come from the installed distributions. The dataset digest comes
    from hashing ``dataset_path``, which must be the release artifact that was
    loaded (what :func:`policyengine.provenance.dataset_materialization.
    materialize_dataset` returns), not a derived per-year file such as
    ``enhanced_frs_2024_25_year_2026.h5``. The certificate is attached only when the
    bundled certification covers the installed model version and those
    dataset bytes; otherwise the receipt is ``uncertified``. ``outputs``,
    when given, is digested as RFC 8785 JSON.

    ``package_hashes`` maps a distribution name to ``(wheel_sha256,
    evidence)`` for hashes the caller verified (for example by checking the
    installed files against the wheel RECORD).
    """

    tro_fingerprint: Optional[str] = None
    if bundle is None:
        from policyengine.provenance.certification import default_bundle_source_path

        manifest_path = default_bundle_source_path()
        bundle = json.loads(manifest_path.read_text())
        tro_fingerprint = _packaged_tro_fingerprint(
            manifest_path.parent / f"{country_id}.trace.tro.jsonld"
        )
    try:
        record = bundle["data_releases"][country_id]
    except KeyError as exc:
        raise ReceiptError(
            f"The bundle has no data release for {country_id!r}."
        ) from exc

    hashes = {
        normalize_distribution_name(key): value
        for key, value in (package_hashes or {}).items()
    }

    def identity(name: str) -> PackageIdentity:
        verified = hashes.get(normalize_distribution_name(name))
        if verified is None:
            return installed_package_identity(name)
        return installed_package_identity(
            name, wheel_sha256=verified[0], wheel_sha256_evidence=verified[1]
        )

    wrapper = _wrapper_identity(wrapper_git_sha)
    if "policyengine" in hashes:
        wrapper = WrapperIdentity(
            **identity("policyengine").model_dump(), git_sha=wrapper_git_sha
        )
    model = identity(_country_model_package(country_id))
    core = identity("policyengine-core")

    dataset_name = dataset or record["default_dataset"]
    reference = (record.get("datasets") or {}).get(dataset_name)
    if reference is None:
        raise ReceiptError(
            f"Dataset {dataset_name!r} is not in the bundled {country_id} release."
        )
    data_package = record.get("data_package") or {}
    certified_artifact = record.get("certified_data_artifact") or {}
    certification = record.get("certification") or {}
    revision = reference.get("revision") or data_package.get("version")
    repo_id = reference.get("repo_id") or data_package.get("repo_id")
    if not revision or not repo_id:
        raise ReceiptError(
            f"Dataset {dataset_name!r} has no repository or revision pin in the bundle."
        )
    actual_sha256 = sha256_file(dataset_path)
    data = DataIdentity(
        data_package=data_package["name"],
        release_version=data_package["version"],
        build_id=certification.get("data_build_id")
        or certified_artifact.get("build_id"),
        build_fingerprint=certification.get("data_build_fingerprint"),
        build_model_version=certification.get("built_with_model_version"),
        release_manifest_revision=data_package.get("release_manifest_revision"),
        dataset=dataset_name,
        dataset_uri=f"hf://{repo_id}/{reference['path']}@{revision}",
        dataset_revision=revision,
        dataset_sha256=actual_sha256,
    )

    certificate = None
    status: Literal["certified", "uncertified"] = "uncertified"
    certified_model = certification.get("certified_for_model_version")
    certified_sha = certified_artifact.get("sha256")
    if (
        certified_model == model.version
        and certified_sha == actual_sha256
        and dataset_name == certified_artifact.get("dataset")
        and bundle.get("policyengine_version") == wrapper.version
        and record.get("policyengine_version", wrapper.version) == wrapper.version
    ):
        certificate = CertificateIdentity(
            bundle_version=wrapper.version,
            country_id=country_id,
            certificate_sha256=certificate_sha256(record),
            compatibility_basis=certification["compatibility_basis"],
            certified_for_model_version=certified_model,
            certified_dataset_sha256=certified_sha,
            certified_by=certification.get("certified_by"),
            qualification_receipt_sha256=qualification_receipt_sha256,
            tro_composition_fingerprint=tro_fingerprint,
        )
        status = "certified"

    return ExecutionReceipt(
        schema_version=RECEIPT_SCHEMA_VERSION,
        receipt_type="policyengine.execution_receipt",
        country_id=country_id,
        wrapper=wrapper,
        model=model,
        core=core,
        data=data,
        certification_status=status,
        certificate=certificate,
        reform=reform or ReformIdentity(kind="current_law"),
        baseline=baseline or ReformIdentity(kind="current_law"),
        fiscal_year=(
            uk_fiscal_year_convention()
            if country_id == "uk"
            else FiscalYearConvention(
                convention="calendar_year",
                period_start="01-01",
                parameter_annualisation="policyengine-us/calendar-year-parameters",
            )
        ),
        years=sorted(set(int(year) for year in years)),
        outputs_sha256=(content_sha256(outputs) if outputs is not None else None),
        runtime=RuntimeContext(
            python_version=platform.python_version(),
            platform=sys.platform,
            ci_run_url=ci_run_url,
        ),
    )


def _packaged_tro_fingerprint(path: Path) -> Optional[str]:
    if not path.is_file():
        return None
    from policyengine.provenance.trace import extract_bundle_tro_reference

    try:
        fingerprint = extract_bundle_tro_reference(json.loads(path.read_text()))[
            "fingerprint"
        ]
    except (ValueError, KeyError):
        return None
    return str(fingerprint) if fingerprint else None


def scenario_reform_identity(
    scenario: Any,
    *,
    code_revision: Optional[Mapping[str, str]] = None,
    name: Optional[str] = None,
) -> ReformIdentity:
    """Bind a policyengine-uk ``Scenario`` by digest.

    The payload is ``{applied_before_data_load, parameter_changes,
    simulation_modifier}``. A ``simulation_modifier`` is arbitrary Python, so
    it is bound by its module, qualified name and source digest together with
    ``code_revision`` (``{"repository": ..., "git_sha": ...}``) of the code
    that defines it, and the identity is marked ``binding="code_revision"``.
    A modifier's closure values are not bound; express reforms as
    ``parameter_changes`` wherever possible.
    """

    import inspect

    parameter_changes = getattr(scenario, "parameter_changes", None) or None
    modifier = getattr(scenario, "simulation_modifier", None)
    if parameter_changes is None and modifier is None:
        return ReformIdentity(kind="current_law", name=name)
    payload: dict[str, Any] = {
        "applied_before_data_load": bool(
            getattr(scenario, "applied_before_data_load", False)
        ),
        "parameter_changes": parameter_changes,
        "simulation_modifier": None,
    }
    binding: Literal["content", "code_revision"] = "content"
    if modifier is not None:
        if not code_revision or not {"repository", "git_sha"} <= set(code_revision):
            raise ReceiptError(
                "A scenario with a simulation_modifier can only be receipted with "
                "code_revision={'repository': ..., 'git_sha': ...} naming the code "
                "that defines the modifier."
            )
        try:
            source = inspect.getsource(modifier)
        except (OSError, TypeError) as exc:
            raise ReceiptError(
                "The simulation_modifier's source is unavailable, so it cannot be bound."
            ) from exc
        payload["simulation_modifier"] = {
            "module": getattr(modifier, "__module__", None),
            "qualname": getattr(modifier, "__qualname__", None),
            "source_sha256": hashlib.sha256(source.encode("utf-8")).hexdigest(),
            "code_revision": dict(code_revision),
        }
        binding = "code_revision"
    digest = content_sha256(
        {"representation": "policyengine-uk.scenario/v1", "payload": payload}
    )
    return ReformIdentity(
        kind="reform",
        representation="policyengine-uk.scenario/v1",
        reform_sha256=digest,
        binding=binding,
        name=name,
    )


def build_execution_receipt_for_microsimulation(
    microsimulation: Any,
    *,
    years: Sequence[int],
    reform: Optional[ReformIdentity] = None,
    baseline: Optional[ReformIdentity] = None,
    outputs: Optional[Any] = None,
    **kwargs: Any,
) -> ExecutionReceipt:
    """Receipt for a country Microsimulation built by ``managed_microsimulation``.

    Reads the dataset that was loaded from ``microsimulation.policyengine_bundle``
    and hashes those bytes. Whether the result is certified follows from the
    bytes and the installed versions, not from how the dataset was selected.
    """

    bundle_fields = getattr(microsimulation, "policyengine_bundle", None)
    if not bundle_fields or not bundle_fields.get("runtime_dataset_source"):
        raise ReceiptError(
            "This microsimulation records no runtime dataset; build it with "
            "managed_microsimulation()."
        )
    country_id = bundle_fields.get("country_id")
    if country_id not in ("uk", "us"):
        raise ReceiptError(f"Unknown country {country_id!r} on the microsimulation.")
    return build_execution_receipt(
        country_id=country_id,
        dataset_path=bundle_fields["runtime_dataset_source"],
        dataset=bundle_fields.get("runtime_dataset"),
        years=years,
        reform=reform,
        baseline=baseline,
        outputs=outputs,
        **kwargs,
    )
