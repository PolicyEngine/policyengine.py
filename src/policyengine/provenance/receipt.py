class ReceiptError(ValueError):
    """Raised when a receipt would claim something the runtime cannot back."""


class _Contract(BaseModel):
    """Strict, immutable, JSON round-trippable contract model.

    Strict mode refuses to coerce (``"2027"`` is not a year), so a parsed
    receipt digests to exactly what was received.
    """

    model_config = ConfigDict(frozen=True, extra="forbid", strict=True)

    def canonical_payload(self) -> dict[str, Any]:
        """The JSON value canonicalized for digests (``None`` members omitted)."""

        return self.model_dump(mode="json", exclude_none=True)


class PackageIdentity(_Contract):
    """A Python distribution that took part in the execution."""

    name: str = Field(
        pattern=DISTRIBUTION_PATTERN,
        description="PEP 503 normalized distribution name, e.g. policyengine-uk.",
    )
    version: str = Field(description="Installed version (importlib.metadata).")
    wheel_sha256: Optional[str] = Field(
        default=None,
        pattern=SHA256_PATTERN,
        description=(
            "SHA-256 of the wheel the installed files came from. Present only "
            "when verified by the receipt builder: by checking the installed "
            "files against the wheel's RECORD, or from the installer's recorded "
            "archive hash."
        ),
    )
    wheel_sha256_evidence: Optional[HashEvidence] = Field(
        default=None, description="How wheel_sha256 was established."
    )

    @model_validator(mode="after")
    def _hash_has_evidence(self) -> PackageIdentity:
        if (self.wheel_sha256 is None) != (self.wheel_sha256_evidence is None):
            raise ValueError(
                "wheel_sha256 and wheel_sha256_evidence must be given together."
            )
        return self


