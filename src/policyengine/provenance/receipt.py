class ExecutionReceipt(_Contract):
    """Schema v1 execution receipt. See the module docstring for its rules."""

    SCHEMA_ID: ClassVar[str] = (
        "https://policyengine.org/schemas/execution_receipt.v1.json"
    )

    schema_version: Literal[1]
    receipt_type: Literal["policyengine.execution_receipt"]
    country_id: Literal["uk"]
    wrapper: WrapperIdentity
    model: PackageIdentity
    core: PackageIdentity
    data: DataIdentity
    certification_status: Literal["certified", "uncertified"]
    certificate: Optional[CertificateIdentity] = None
    reform: ReformIdentity
    baseline: ReformIdentity
    fiscal_year: FiscalYearConvention
    years: list[int] = Field(min_length=1)
    outputs_sha256: Optional[str] = Field(
        default=None,
        pattern=SHA256_PATTERN,
        description="content_sha256 of the canonical output payload this receipt binds.",
    )
    runtime: Optional[RuntimeContext] = None

    @field_validator("years")
    @classmethod
    def _sorted_unique_years(cls, years: list[int]) -> list[int]:
        if years != sorted(set(years)):
            raise ValueError("years must be sorted and unique.")
        return years

    @model_validator(mode="after")
    def _identity_rules(self) -> ExecutionReceipt:
        if self.fiscal_year.convention != "uk_fiscal_year":
            raise ValueError("UK receipts report uk_fiscal_year periods.")
        for role, expected in UK_PACKAGES.items():
            actual = getattr(self, role).name
            if actual != expected:
                raise ValueError(f"{role} must be {expected}, not {actual}.")
        if self.certification_status == "uncertified":
            if self.certificate is not None:
                raise ValueError("An uncertified receipt carries no certificate.")
            return self
        certificate = self.certificate
        if certificate is None:
            raise ValueError("A certified receipt needs a certificate.")
        if certificate.country_id != self.country_id:
            raise ValueError("Certificate country differs from the receipt country.")
        if certificate.certified_for_model_version != self.model.version:
            raise ValueError(
                f"The certificate covers model {certificate.certified_for_model_version}, "
                f"but {self.model.version} ran."
            )
        if certificate.certified_for_core_version != self.core.version:
            raise ValueError(
                f"The certificate covers core {certificate.certified_for_core_version}, "
                f"but {self.core.version} ran."
            )
        if certificate.certified_dataset_sha256 != self.data.dataset_sha256:
            raise ValueError(
                "The certificate covers different dataset bytes from those simulated."
            )
        if certificate.bundle_version != self.wrapper.version:
            raise ValueError(
                "The certificate belongs to a different policyengine.py version."
            )
        return self

    # --- Digests ---------------------------------------------------------
    def execution_identity(self) -> dict[str, Any]:
        """The canonical value that identifies the runtime, data and certificate."""

        identity: dict[str, Any] = {
            "schema_version": self.schema_version,
            "country_id": self.country_id,
            "wrapper": self.wrapper.canonical_payload(),
            "model": self.model.canonical_payload(),
            "core": self.core.canonical_payload(),
            "data": self.data.canonical_payload(),
            "certification_status": self.certification_status,
        }
        if self.certificate is not None:
            payload = self.certificate.canonical_payload()
            identity["certificate"] = {
                key: payload[key]
                for key in CertificateIdentity.IDENTITY_FIELDS
                if key in payload
            }
        return identity

    @property
    def execution_identity_sha256(self) -> str:
        return canonical_sha256(self.execution_identity())

    def receipt_payload(self) -> dict[str, Any]:
        """What the receipt digest covers: no runtime context, no labels."""

        payload = self.canonical_payload()
        payload.pop("runtime", None)
        for key in ("reform", "baseline"):
            payload[key].pop("name", None)
        return payload

    @property
    def receipt_sha256(self) -> str:
        return canonical_sha256(self.receipt_payload())

    def to_canonical_json(self) -> bytes:
        """RFC 8785 bytes of the full receipt, including runtime context."""

        return canonical_json(self.canonical_payload())

    @classmethod
    def json_schema(cls) -> dict[str, Any]:
        """JSON Schema (2020-12), with the rules it cannot express attached."""

        schema = cls.model_json_schema()
        return {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": cls.SCHEMA_ID,
            **schema,
            "x-policyengine-rules": list(CROSS_FIELD_RULES),
            "x-policyengine-digests": dict(DIGEST_RULES),
        }


# --- Strict JSON values -------------------------------------------------------


def _numpy_scalar(value: Any) -> bool:
    module = type(value).__module__
    return (
        module.startswith("numpy")
        and hasattr(value, "item")
        and getattr(value, "ndim", 0) == 0
    )


def strict_json_value(value: Any, path: str = "$") -> Any:
    """Convert to a JSON value, refusing anything without one exact JSON form.

    Accepted: ``None``, booleans, strings, integers (including ``IntEnum`` and
    numpy integer scalars), finite floats (including numpy float scalars),
    ``datetime.date`` (as ISO 8601, ``YYYY-MM-DD``), lists and tuples, and
    mappings whose keys are strings or integers (integers become their
    decimal string; a key collision is refused). Everything else (sets,
    ``Decimal``, bytes, arrays, objects) raises :class:`ReceiptError`, so no
    value is silently stringified.
    """

    if value is None or isinstance(value, (bool, str)):
        return value
    if _numpy_scalar(value):
        return strict_json_value(value.item(), path)
    if isinstance(value, int):
        return int(value)
    if isinstance(value, float):
        number = float(value)
        if not math.isfinite(number):
            raise ReceiptError(f"{path}: {number} is not a finite number.")
        return number
    if isinstance(value, datetime.datetime):
        raise ReceiptError(f"{path}: datetimes are ambiguous; pass an ISO 8601 string.")
    if isinstance(value, datetime.date):
        return value.isoformat()
    if isinstance(value, Mapping):
        result: dict[str, Any] = {}
        for key, item in value.items():
            if isinstance(key, bool) or not isinstance(key, (str, int)):
                raise ReceiptError(f"{path}: object keys must be strings, not {key!r}.")
            text = key if isinstance(key, str) else str(int(key))
            if text in result:
                raise ReceiptError(f"{path}: keys {key!r} and {text!r} collide.")
            result[text] = strict_json_value(item, f"{path}.{text}")
        return result
    if isinstance(value, (list, tuple)):
        return [
            strict_json_value(item, f"{path}[{index}]")
            for index, item in enumerate(value)
        ]
    raise ReceiptError(
        f"{path}: {type(value).__name__} has no exact JSON form; convert it first."
    )


def content_sha256(value: Any) -> str:
    """Receipt digest of a value: strict JSON, nulls dropped, RFC 8785, SHA-256."""

    return canonical_sha256(drop_null_members(strict_json_value(value)))


