RECEIPT_SCHEMA_VERSION: Literal[1] = 1

SHA256_PATTERN = r"^[0-9a-f]{64}$"
GIT_SHA_PATTERN = r"^[0-9a-f]{40}$"
_SHA256 = re.compile(SHA256_PATTERN)

#: Reform representations whose digests a receipt can carry. Different
#: representations can legitimately mean different things for the same
#: keys (a country-dict bare year changes one year; ``Reform.from_dict``
#: continues after it), so a digest is always taken together with its
#: representation and never normalized across representations.
ReformRepresentation = Literal[
    # ``policyengine.core.run_record.reform_specification`` without ``name``:
    # sorted ``{parameter, value, start_date, end_date}`` entries.
    "policyengine.parameter_values/v1",
    # A wrapper dictionary policy: ``{parameter_path: {date_key: value}}``.
    "policyengine.reform_dict/v1",
    # A policyengine-uk country dictionary reform as passed to
    # ``Scenario.from_reform`` / ``Simulation(reform=...)``.
    "policyengine-uk.reform_dict/v1",
    # A request body sent to the simulation API.
    "policyengine-sim-api.policy/v1",
    # A policyengine-uk ``Scenario``: see scenario_reform_identity().
    "policyengine-uk.scenario/v1",
]


#: v1 rules that JSON Schema cannot express. Published in the schema file.
CROSS_FIELD_RULES: tuple[str, ...] = (
    "years is sorted ascending with no duplicates.",
    "country_id uk reports fiscal_year.convention uk_fiscal_year; us reports calendar_year.",
    "certification_status certified requires certificate; uncertified forbids it.",
    "certificate.country_id equals country_id.",
    "certificate.certified_for_model_version equals model.version.",
    "certificate.certified_dataset_sha256 equals data.dataset_sha256.",
    "certificate.bundle_version equals wrapper.version.",
    "reform/baseline kind current_law has no representation or reform_sha256 and binding content; kind reform has both.",
    "wheel_sha256 and wheel_sha256_evidence are present together or not at all.",
)

#: How each digest is computed. Every digest is the lowercase hex SHA-256 of
#: the RFC 8785 canonical JSON of the stated value, with null members removed.
DIGEST_RULES: dict[str, str] = {
    "canonicalization": "RFC 8785 (JSON Canonicalization Scheme); object members whose value is null are removed before canonicalizing.",
    "execution_identity_sha256": "{schema_version, country_id, wrapper, model, core, data, certification_status, certificate?}",
    "receipt_sha256": "the whole receipt without runtime",
    "certificate.certificate_sha256": "the bundle manifest's data_releases.<country_id> record",
    "reform.reform_sha256": "{representation, payload} where payload is the reform exactly as given in that representation",
    "outputs_sha256": "the canonical output payload the receipt binds",
}


HashEvidence = Literal["installed_record_verified", "installer_archive_hash"]


class ReceiptError(ValueError):
    """Raised when a receipt would claim something the runtime cannot back."""


class _Contract(BaseModel):
    """Strict, immutable, JSON round-trippable contract model."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    def canonical_payload(self) -> dict[str, Any]:
        """The JSON value that is canonicalized for digests.

        ``None`` members are omitted so that adding an optional field in a
        compatible v1 revision does not change existing digests.
        """

        return self.model_dump(mode="json", exclude_none=True)


class PackageIdentity(_Contract):
    """A Python distribution that took part in the execution."""

    name: str = Field(description="Normalized distribution name, e.g. policyengine-uk.")
    version: str = Field(description="Installed version (importlib.metadata).")
    wheel_sha256: Optional[str] = Field(
        default=None,
        pattern=SHA256_PATTERN,
        description=(
            "SHA-256 of the wheel the installed files came from. Present only "
            "when verified: by checking the installed files against the wheel's "
            "RECORD, or by the installer's recorded archive hash."
        ),
    )
    wheel_sha256_evidence: Optional[
        Literal["installed_record_verified", "installer_archive_hash"]
    ] = Field(
        default=None,
        description="How ``wheel_sha256`` was established.",
    )

    @field_validator("name")
    @classmethod
    def _normalize_name(cls, value: str) -> str:
        return normalize_distribution_name(value)

    @model_validator(mode="after")
    def _hash_has_evidence(self) -> PackageIdentity:
        if (self.wheel_sha256 is None) != (self.wheel_sha256_evidence is None):
            raise ValueError(
                "wheel_sha256 and wheel_sha256_evidence must be given together."
            )
        return self


class WrapperIdentity(PackageIdentity):
    """The policyengine.py distribution, optionally pinned to a source commit."""

    git_sha: Optional[str] = Field(
        default=None,
        pattern=GIT_SHA_PATTERN,
        description="policyengine.py commit, when running from a checkout.",
    )


